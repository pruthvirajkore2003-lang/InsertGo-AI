async function atomicWrite(targetPath, content) {
  const normalized = `${content.trimEnd()}\n`;
  const current = (await exists(targetPath))
    ? await readFile(targetPath, "utf8")
    : null;
  if (current === normalized) return false;

  const temporaryPath = `${targetPath}.${process.pid}.tmp`;
  try {
    await writeFile(temporaryPath, normalized, "utf8");
    try {
      await rename(temporaryPath, targetPath);
    } catch (error) {
      if (!["EEXIST", "EPERM"].includes(error.code)) throw error;
      await copyFile(temporaryPath, targetPath);
    }
  } finally {
    await rm(temporaryPath, { force: true });
  }
  return true;
}

async function syncFiles(directory, targets, content) {
  if (!(await exists(directory))) {
    warnings.push(`missing project: ${directory}`);
    return [];
  }

  const changed = [];
  for (const name of targets) {
    const targetPath = path.join(directory, name);
    if (await atomicWrite(targetPath, content)) changed.push(targetPath);
  }
  return changed;
}

async function syncProject(directory, content, extraTargets = []) {
  return syncFiles(
    directory,
    [...canonicalTargets, ...extraTargets],
    content,
  );
}

