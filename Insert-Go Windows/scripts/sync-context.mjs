async function exists(filePath) {
  try {
    await access(filePath);
    return true;
  } catch {
    return false;
  }
}

async function readJson(filePath) {
  let source;
  try {
    source = await readFile(filePath, "utf8");
  } catch (error) {
    if (error.code === "ENOENT") {
      warnings.push(`missing source: ${filePath}`);
      return {};
    }
    throw error;
  }

  let value;
  try {
    value = JSON.parse(source);
  } catch (error) {
    throw new Error(`invalid JSON in ${filePath}: ${error.message}`);
  }
  if (!value || Array.isArray(value) || typeof value !== "object") {
    throw new Error(`expected JSON object in ${filePath}`);
  }
  return value;
}

function dependencyVersion(manifest, name, fallback = "not declared") {
  return (
    manifest.dependencies?.[name] ??
    manifest.devDependencies?.[name] ??
    fallback
  );
}

function majorVersion(version, fallback) {
  const match = String(version).match(/\d+/);
  return match ? `v${match[0]}` : fallback;
}

async function rustVersion() {
  const cargoPath = path.join(desktopDir, "src-tauri", "Cargo.toml");
  try {
    const cargo = await readFile(cargoPath, "utf8");
    return cargo.match(/^\s*rust-version\s*=\s*"([^"]+)"/m)?.[1] ?? "1.85";
  } catch (error) {
    if (error.code === "ENOENT") {
      warnings.push(`missing source: ${cargoPath}`);
      return "1.85";
    }
    throw error;
  }
}

